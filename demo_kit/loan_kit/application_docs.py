"""Application-stage loan documents, aligned with the processing prompts.

Rendering-agnostic content: every builder returns a list of pages, each a
(title, lines) pair. A line is plain text, "## Heading", or "@@Label|Value"
(a label/value row laid out the way loan_extractors._labelled reads it).
application_kit.py renders these as PDF (minipdf) and Excel (minixlsx) for
demo_kit/loan_kit/bundles*; samples/build_email_packs.py renders the same
content as email-intake packs.

Six packs, one fictional applicant each, built against the criteria in
loan_processing.DEFAULT_PROMPTS for home / vehicle / personal loans:

    home_loan_application_positive       ELIGIBLE
    home_loan_application_negative       NOT_ELIGIBLE  (+ a tampered salary slip)
    vehicle_loan_application_positive    ELIGIBLE
    vehicle_loan_application_negative    NOT_ELIGIBLE
    personal_loan_application_positive   ELIGIBLE
    personal_loan_application_negative   NOT_ELIGIBLE

Salary slips carry the exact labels and western money format the
deterministic extractor parses, so they reconcile in code. No document other
than a salary slip may contain an extractor type marker ("SALARY SLIP",
"SANCTION LETTER", ...) — the engine would parse it as that type and lose it.
Every page is stamped SPECIMEN; nothing here is a real person or record.
"""
from __future__ import annotations

from dataclasses import dataclass

STAMP = ("SPECIMEN - synthetic demo data generated by application_docs.py. "
         "Not a real customer, account or document.")
MONTHS = ["March 2026", "April 2026", "May 2026", "June 2026", "July 2026", "August 2026"]
BANK_MONTHS = [("01-03-2026", "31-03-2026"), ("01-04-2026", "30-04-2026"),
               ("01-05-2026", "31-05-2026"), ("01-06-2026", "30-06-2026"),
               ("01-07-2026", "31-07-2026"), ("01-08-2026", "31-08-2026")]


def money(v: float) -> str:
    """Western grouping with two decimals - the only form the extractor reads."""
    return f"{v:,.2f}"


def emi_for(principal: float, annual_rate: float, months: int) -> float:
    r = annual_rate / 1200.0
    return round(principal * r * (1 + r) ** months / ((1 + r) ** months - 1), 2)


# ── The applicant ──────────────────────────────────────────────────────
@dataclass
class Applicant:
    name: str
    dob: str          # dd-mm-yyyy
    age: int
    pan: str
    aadhaar: str      # masked
    address: str
    employer: str
    designation: str
    years_in_job: int
    basic: float
    hra: float
    special: float
    pf: float
    tds: float
    account: str
    ifsc: str
    bank: str
    phone: str

    @property
    def gross(self) -> float:
        return round(self.basic + self.hra + self.special, 2)

    @property
    def deductions(self) -> float:
        return round(self.pf + self.tds, 2)

    @property
    def net(self) -> float:
        return round(self.gross - self.deductions, 2)


