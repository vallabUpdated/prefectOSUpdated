def salary_pages(a: Applicant, months=MONTHS, tamper_gross: float | None = None):
    """Six slips laid out exactly as loan_extractors.parse_salary_slip reads:
    `Label   value` rows, western money, NET PAY in capitals."""
    pages = []
    for i, month in enumerate(months):
        # The extractor reads the FIRST slip in the file, so a seeded tamper
        # goes on slip 1 (March) to be caught in code.
        tampered = bool(tamper_gross) and i == 0
        gross = tamper_gross if tampered else a.gross
        net = round(gross - a.deductions, 2) if tampered else a.net
        pages.append((f"SALARY SLIP - {month}", [
            f"Employer: {a.employer}",
            f"@@Employee|{a.name}",
            f"@@Employee ID|EMP-{a.pan[-4:]}",
            f"@@Designation|{a.designation}",
            f"PAN: {a.pan}        Bank A/c: {a.account}",
            "", "## Earnings",
            f"@@Basic|{money(a.basic)}",
            f"@@HRA|{money(a.hra)}",
            f"@@Special Allowance|{money(a.special)}",
            f"@@Gross Earnings|{money(gross)}",
            "", "## Deductions",
            f"@@Provident Fund|{money(a.pf)}",
            f"@@Income Tax (TDS)|{money(a.tds)}",
            f"@@Total Deductions|{money(a.deductions)}",
            "",
            f"@@NET PAY|{money(net)}",
            "", "Computer generated; no signature required.",
        ]))
    pages.append(("FORM 16 - Certificate under section 203 of the Income-tax Act (FY 2025-26)", [
        f"Employer: {a.employer}        TAN: BLR{a.pan[:5]}A",
        f"Employee: {a.name}        PAN: {a.pan}",
        f"Period of employment in FY: full year        Years with employer: {a.years_in_job}",
        "",
        f"@@Gross salary (total income from salary)|{money(a.gross * 12)}",
        f"@@Total income|{money(a.gross * 12 - a.pf * 12)}",
        f"@@Tax deducted at source|{money(a.tds * 12)}",
        "", "Verified by: Head of Finance",
    ]))
    return pages


def bank_statement_pages(a: Applicant, salary_credit: float, extra_debits=(), label_note=""):
    """Six monthly savings statements with the salary credit each month.
    Never says 'LOAN ACCOUNT STATEMENT' or 'SALARY SLIP' (other parsers)."""
    pages = []
    balance = 214_500.00
    for (start, end), month in zip(BANK_MONTHS, MONTHS):
        rows = [(start, "Opening balance", "", "", balance)]
        balance = round(balance + salary_credit, 2)
        rows.append((start, f"NEFT SALARY {a.employer.split()[0].upper()}", "", salary_credit, balance))
        for day, desc, amt in (("05", "UPI RENT", 38_000.00), ("09", "CARD PAYMENT", 22_400.00),
                               ("14", "UPI GROCERIES", 6_240.00), ("20", "INSURANCE PREMIUM", 8_500.00)):
            balance = round(balance - amt, 2)
            rows.append((f"{day}-{start[3:]}", desc, amt, "", balance))
        for day, desc, amt in extra_debits:
            balance = round(balance - amt, 2)
            rows.append((f"{day}-{start[3:]}", desc, amt, "", balance))
        rows.append((end, "Closing balance", "", "", balance))
        lines = [f"{a.bank} - Savings account statement",
                 f"Account holder: {a.name}",
                 f"Account number: {a.account}        IFSC: {a.ifsc}",
                 f"Statement period: {start} to {end}", "",
                 "Date         Transaction                      Debit         Credit        Balance"]
        for d, desc, dr, cr, bal in rows:
            lines.append(f"{d:<12} {desc:<30} {money(dr) if dr else '':>12}  {money(cr) if cr else '':>12}  {money(bal):>14}")
        lines += ["", f"Opening balance: {money(rows[0][4])}        Closing balance: {money(balance)}",
                  f"Salary credit this month: {money(salary_credit)}"]
        if label_note:
            lines.append(label_note)
        pages.append((f"ACCOUNT STATEMENT - {month}", lines))
    return pages


