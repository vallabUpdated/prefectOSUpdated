def application_pages(a: Applicant, product_label: str, amount: float, months: int, rate: float,
                      purpose: str, extra_lines: list[str], enclosed: list[str],
                      existing_emi: float = 0.0, active_unsecured: int = 0):
    emi = emi_for(amount, rate, months)
    return [("LOAN APPLICATION FORM", [
        f"Product applied: {product_label}",
        f"Applicant name: {a.name}",
        f"Date of birth: {a.dob} (age {a.age})        PAN: {a.pan}        Aadhaar: {a.aadhaar}",
        f"Residential address: {a.address}",
        f"Mobile: {a.phone}",
        "", "## Loan requested",
        f"@@Loan amount (Rs)|{money(amount)}",
        f"@@Tenure|{months} months",
        f"@@Interest rate|{rate:.2f}% p.a.",
        f"@@Proposed EMI (Rs)|{money(emi)}",
        f"Age at loan maturity: {a.age + months // 12}",
        f"Purpose: {purpose}",
        *extra_lines,
        "", "## Employment and income",
        f"Employer: {a.employer}        Designation: {a.designation}",
        f"Employment type: Salaried        Years in current job: {a.years_in_job}",
        f"@@Gross monthly income (Rs)|{money(a.gross)}",
        f"@@Net monthly income (Rs)|{money(a.net)}",
        f"@@EMI to net income|{emi / a.net * 100:.2f}%",
        "", "## Existing obligations",
        f"@@Existing EMIs per month (Rs)|{money(existing_emi)}",
        f"Active unsecured loans: {active_unsecured}",
        "", "## Declaration",
        "I declare that the information given in this loan application is true and complete.",
        f"Signature: {a.name}        Date: 01-09-2026",
    ]), ("LOAN APPLICATION FORM - Annexure: documents enclosed", [
        "## Documents enclosed with this loan application",
        *(f"  - {d}" for d in enclosed),
    ])], emi


