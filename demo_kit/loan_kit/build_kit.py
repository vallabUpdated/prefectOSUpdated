"""Regenerate the sample loan-processing kit.

    python demo_kit/loan_kit/build_kit.py

Everything under `bundles/` is written from here, so the arithmetic in the
documents is computed rather than typed: a clean bundle reconciles to the last
paisa, and a defective one carries exactly the defects seeded below and no
others. That is what makes the kit safe to run in front of a client — the
engine's findings are known in advance.

The documents are synthetic. Every page carries a SPECIMEN stamp, the
identifiers are obviously fake, and no figure comes from a real customer.
"""

