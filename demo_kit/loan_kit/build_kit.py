def money(v: float) -> str:
    return f"{v:,.2f}"


def emi_for(principal: float, annual_rate: float, months: int) -> float:
    r = annual_rate / 1200.0
    return round(principal * r * (1 + r) ** months / ((1 + r) ** months - 1), 2)


def amortise(principal: float, annual_rate: float, emi: float,
             first_due: date, rows: int) -> list[dict]:
    """The schedule the engine will recompute, row by row, in exactly this way."""
    r = annual_rate / 1200.0
    out, balance, due = [], principal, first_due
    for n in range(1, rows + 1):
        interest = round(balance * r, 2)
        principal_part = round(emi - interest, 2)
        balance = round(balance - principal_part, 2)
        out.append({"no": n, "due": due.isoformat(), "emi": emi,
                    "interest": interest, "principal": principal_part,
                    "balance": balance})
        due = _add_month(due)
    return out


def _add_month(d: date) -> date:
    year, month = (d.year + 1, 1) if d.month == 12 else (d.year, d.month + 1)
    return date(year, month, min(d.day, 28))


# ── shared page furniture ────────────────────────────────────────────────────

def _header(p: Page, institution: str, title: str, subtitle: str = "") -> float:
    p.band(LEFT, 48, RIGHT, 34)
    p.text(LEFT + 10, 70, institution, 12, bold=True)
    p.right(RIGHT - 10, 70, title, 12, bold=True)
    if subtitle:
        p.right(RIGHT, 98, subtitle, 8, gray=0.35)
    return 116.0


def _footer(p: Page) -> None:
    p.rule(LEFT, 790, RIGHT, 0.5, 0.8)
    p.text(LEFT, 802, STAMP, 7, gray=0.45)


def _labelled(p: Page, y: float, label: str, value: str,
              money_col: float | None = None, bold: bool = False) -> float:
    """A `Label      Value` row — the shape `loan_extractors._labelled` reads."""
    p.text(LEFT, y, label, 9, bold=bold)
    if money_col is not None:
        p.right(money_col, y, value, 9, bold=bold)
    else:
        p.text(LEFT + 190, y, value, 9, bold=bold)
    return y + 16


