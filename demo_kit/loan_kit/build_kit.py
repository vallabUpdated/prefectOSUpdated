def _schedule_totals(schedule: list[dict]) -> dict:
    return {"interest": round(sum(r["interest"] for r in schedule), 2),
            "principal": round(sum(r["principal"] for r in schedule), 2),
            "closing": schedule[-1]["balance"]}


def _ledger_totals(txns: list[dict]) -> dict:
    return {"debits": round(sum(t["debit"] for t in txns), 2),
            "credits": round(sum(t["credit"] for t in txns), 2),
            "closing": txns[-1]["balance"]}


def build_bundle(out: Path, spec: dict, xl_out: Path | None = None) -> dict:
    """Write one applicant's document set. Returns the facts the runbook quotes.

    `xl_out` writes the same documents again as .xlsx, from the same computed
    figures — so a seeded defect reads identically in both formats.
    """
    true_emi = emi_for(spec["principal"], spec["rate"], spec["months"])
    printed_emi = round(true_emi - spec.get("emi_understated", 0.0), 2)

    sanction_letter(out / "01_sanction_letter.pdf", spec["bank"],
                    spec["loan_id"], spec["borrower"], spec["address"],
                    spec["product"], spec["principal"], spec["rate"],
                    spec["months"], printed_emi, spec["fee"],
                    spec["first_emi"], spec["issued"])
    if xl_out:
        xl_sanction_letter(xl_out / "01_sanction_letter.xlsx", spec, printed_emi)

    gross = spec["basic"] + spec["hra"] + spec["special"]
    deductions = spec["pf"] + spec["tax"]
    # An understated deductions column flatters take-home pay while every other
    # figure on the slip still adds up — net pay follows the stated total, so
    # only the deductions line is wrong.
    stated_deductions = round(deductions - spec.get("deductions_understated", 0.0), 2)
    printed_net = round(gross - stated_deductions
                        + spec.get("net_pay_overstated", 0.0), 2)
    salary_slip(out / "02_salary_slip.pdf", spec["employer"], spec["period"],
                spec["borrower"], spec["employee_id"], spec["designation"],
                basic=spec["basic"], hra=spec["hra"], special=spec["special"],
                pf=spec["pf"], tax=spec["tax"], deductions=stated_deductions,
                net_pay=printed_net)
    if xl_out:
        xl_salary_slip(xl_out / "02_salary_slip.xlsx", spec["employer"],
                       spec["period"], spec["borrower"], spec["employee_id"],
                       spec["designation"], spec["basic"], spec["hra"],
                       spec["special"], spec["pf"], spec["tax"], gross,
                       stated_deductions, printed_net)

    schedule = amortise(spec["principal"], spec["rate"], true_emi,
                        spec["first_due"], 12)
    totals = None
    if spec.get("schedule_totals_delta"):
        # The rows are all correct; the totals line under them is not. The
        # reader re-adds the column and catches the difference.
        totals = {"interest": round(sum(r["interest"] for r in schedule)
                                    + spec["schedule_totals_delta"], 2),
                  "principal": round(sum(r["principal"] for r in schedule), 2),
                  "closing": schedule[-1]["balance"]}
    if spec.get("tamper_row"):
        # State the true totals, then alter one closing balance: the chain
        # breaks at that row and again at the next, where it re-joins the
        # true figures. Nothing else in the document moves.
        totals = {"interest": round(sum(r["interest"] for r in schedule), 2),
                  "principal": round(sum(r["principal"] for r in schedule), 2),
                  "closing": schedule[-1]["balance"]}
        i = spec["tamper_row"] - 1
        schedule[i]["balance"] = round(schedule[i]["balance"]
                                       - spec["tamper_amount"], 2)
    emi_schedule(out / "03_emi_schedule.pdf", spec["bank"], spec["loan_id"],
                 spec["borrower"], spec["principal"], spec["rate"],
                 spec["months"], true_emi, schedule, totals)
    if xl_out:
        xl_emi_schedule(xl_out / "03_emi_schedule.xlsx", spec, true_emi,
                        schedule, totals or _schedule_totals(schedule))

    if spec.get("statement_months"):
        ledger = loan_ledger(spec["principal"], spec["rate"], true_emi,
                             spec["first_due"], spec["statement_months"], "TXN")
        stated = None
        if spec.get("statement_closing_delta"):
            stated = {"debits": round(sum(t["debit"] for t in ledger), 2),
                      "credits": round(sum(t["credit"] for t in ledger), 2),
                      "closing": round(ledger[-1]["balance"]
                                       - spec["statement_closing_delta"], 2)}
        if spec.get("statement_break_index"):
            # One running balance that does not follow from the row above it.
            # The totals still tie, because a middle row is altered and the
            # closing balance is not — the break is the only finding.
            i = spec["statement_break_index"] - 1
            ledger[i]["balance"] = round(ledger[i]["balance"]
                                         - spec["statement_break_amount"], 2)

        last = ledger[-1]["date"]
        # `statement_borrower` seeds a name that disagrees with the rest of the
        # file — the documents reconcile individually and still do not describe
        # one applicant.
        borrower = spec.get("statement_borrower") or spec["borrower"]
        period = (ledger[0]["date"], last)
        loan_statement(out / "04_loan_account_statement.pdf", spec["bank"],
                       spec["loan_id"], borrower, spec["product"],
                       period, spec["principal"], ledger, stated)
        if xl_out:
            xl_loan_statement(xl_out / "04_loan_account_statement.xlsx", spec,
                              borrower, period, ledger,
                              stated or _ledger_totals(ledger))

    return {"emi": true_emi, "printed_emi": printed_emi,
            "net_pay": printed_net,
            "foir": round(printed_emi / printed_net * 100, 2)}


