    # folder via .gitkeep because it cannot carry an empty directory.
    output = KIT / "output"
    output.mkdir(exist_ok=True)
    (output / ".gitkeep").write_text("", encoding="utf-8")

    facts: dict[str, dict] = {}
    for name, spec in BUNDLE_SPECS.items():
        folder = BUNDLES / name
        xl_folder = BUNDLES_XL / name
