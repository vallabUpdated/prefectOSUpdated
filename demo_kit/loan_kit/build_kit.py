def loan_ledger(opening: float, rate: float, emi: float, start: date,
                periods: int, prefix: str) -> list[dict]:
    """Interest charged, EMI received, month after month — a chain that ties."""
    txns, balance, when = [], opening, start
    for i in range(periods):
        interest = round(balance * rate / 1200.0, 2)
        balance = round(balance + interest, 2)
        txns.append({"date": when.isoformat(), "ref": prefix + "%04d" % (i * 2 + 1),
                     "particulars": "Interest charged", "debit": interest,
                     "credit": 0.0, "balance": balance})
        pay = when + timedelta(days=4)
        balance = round(balance - emi, 2)
        txns.append({"date": pay.isoformat(), "ref": prefix + "%04d" % (i * 2 + 2),
                     "particulars": "EMI received - NACH", "debit": 0.0,
                     "credit": emi, "balance": balance})
        when = _add_month(when)
    return txns


