def current_account_csv(path: Path, opening: float, rows: list[tuple]) -> None:
    """`Date, Chq/Ref No, Narration, Withdrawal Amt, Deposit Amt, Closing Balance`

    Deliberately not the canonical header names — the reader matches columns by
    synonym, and a demo should show that rather than a hand-tailored export.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    balance = opening
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["Meridian Bank - Current Account Statement"])
        w.writerow(["Account", "MB-CA-88214301", "Customer",
                    "Halcyon Traders LLP (SPECIMEN)"])
        w.writerow([])
        w.writerow(["Date", "Chq/Ref No", "Narration", "Withdrawal Amt",
                    "Deposit Amt", "Closing Balance"])
        for when, ref, narration, debit, credit in rows:
            balance = round(balance - debit + credit, 2)
            w.writerow([when, ref, narration,
                        f"{debit:.2f}" if debit else "",
                        f"{credit:.2f}" if credit else "",
                        f"{balance:.2f}"])


