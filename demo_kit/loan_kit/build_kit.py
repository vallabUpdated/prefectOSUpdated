# ── salary slip ──────────────────────────────────────────────────────────────

def salary_slip(path: Path, employer: str, period: str, employee: str,
                employee_id: str, designation: str, basic: float, hra: float,
                special: float, pf: float, tax: float,
                gross: float | None = None, deductions: float | None = None,
                net_pay: float | None = None) -> None:
    gross = round(basic + hra + special, 2) if gross is None else gross
    deductions = round(pf + tax, 2) if deductions is None else deductions
    net_pay = round(gross - deductions, 2) if net_pay is None else net_pay

    pdf = Pdf()
    p = pdf.page()
    y = _header(p, employer, "SALARY SLIP - " + period.upper(),
                "Computer generated statement of earnings")

    # `Employee` must precede `Employee ID`: the reader matches on the row's
    # leading text and keeps the first row that starts with the label.
    y = _labelled(p, y, "Employee", employee)
    y = _labelled(p, y, "Employee ID", employee_id)
    y = _labelled(p, y, "Designation", designation)
    y += 14

    p.band(LEFT, y - 12, RIGHT, 18)
    p.text(LEFT + 6, y, "EARNINGS", 9, bold=True)
    p.right(330, y, "Amount (Rs)", 9, bold=True)
    y += 24
    y = _labelled(p, y, "Basic", money(basic), 330)
    y = _labelled(p, y, "HRA", money(hra), 330)
    y = _labelled(p, y, "Special Allowance", money(special), 330)
    p.rule(LEFT, y - 10, 330)
    y = _labelled(p, y, "Gross Earnings", money(gross), 330, True)
    y += 16

    p.band(LEFT, y - 12, RIGHT, 18)
    p.text(LEFT + 6, y, "DEDUCTIONS", 9, bold=True)
    p.right(330, y, "Amount (Rs)", 9, bold=True)
    y += 24
    y = _labelled(p, y, "Provident Fund", money(pf), 330)
    y = _labelled(p, y, "Income Tax (TDS)", money(tax), 330)
    p.rule(LEFT, y - 10, 330)
    y = _labelled(p, y, "Total Deductions", money(deductions), 330, True)
    y += 22

    p.rule(LEFT, y - 12, 330, 1.0, 0.4)
    y = _labelled(p, y, "NET PAY", money(net_pay), 330, True)
    y += 22
    p.text(LEFT, y, "Credited to the salary account on the last working day of "
                    "the month.", 8.5, gray=0.3)
    _footer(p)
    pdf.save(path)


